data class Post(
    val id: Int = 0,                    //Идентификатор записи.
    val ownerId: Int = 0,               //Идентификатор владельца стены, на которой размещена запись.
    val fromId: Int = 0,                //Идентификатор автора записи (от чьего имени опубликована запись).
    val createdBy: Int = 0,             //Идентификатор администратора, который опубликовал запись
    val date: Long = 0L,                //Время публикации записи в формате Long
    val text: String? = null,           //Текст записи. Может не быть записи, может есть только картинка или это репост.
    val replyOwnerId: Int? = null,      //Идентификатор владельца записи, в ответ на которую была оставлена текущая. Ответа на пост может не быть, поэтому null допустим
    val replyPostId: Int? = null,       //Идентификатор записи, в ответ на которую была оставлена текущая. Ответа на пост может не быть, поэтому null допустим
    val friendsOnly: Boolean = false,   //В VK это integer 0/1, но по логике Boolean
    val comments: Comments? = null,     //Информация о комментариях к записи, объект с полями. Могут и отсутствовать комментарии в посту.
    val likes: Likes? = null,           //Информация о лайках к записи, объект с полями. Лайков может не быть у записи.
    val repostsCount: Int = 0,          //Счетчик репостов
    val postType: String = "post",      //Тип записи, может принимать следующие значения: post, copy, reply, postpone, suggest.
    val signerId: Int = 0,              //Идентификатор автора, если запись была опубликована от имени сообщества и подписана пользователем;
    val canPin: Boolean = true,         //Информация о том, может ли текущий пользователь закрепить запись (1 — может, 0 — не может).
    val canDelete: Boolean = true,      //Информация о том, может ли текущий пользователь удалить запись (1 — может, 0 — не может).
    val canEdit: Boolean = true,        //Информация о том, может ли текущий пользователь редактировать запись (1 — может, 0 — не может).
    val isPinned: Boolean = false,      //Информация о том, что запись закреплена.
    val markedAsAds: Boolean = false,   //Информация о том, содержит ли запись отметку «реклама» (1 — да, 0 — нет).
    val isFavorite: Boolean = false,     //true, если объект добавлен в закладки у текущего пользователя.
    val attachment: List<IntAttachment> = emptyList(), //массив вложений.
)
